import { _electron as electron, expect, test, type ElectronApplication } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

test('tasks, linked reminders, learning records and editable recitation persist on the desktop', async () => {
  const root = resolve(import.meta.dirname, '../../..');
  const folder = await mkdtemp(join(tmpdir(), 'Herta 学习界面 '));
  const env = { ...Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('HERTA_') && !['ELECTRON_RUN_AS_NODE', 'WEB_CONCURRENCY'].includes(key))), HERTA_SERVICE_PROVIDER: 'demo', HERTA_DESKTOP_DATA_DIR: folder } as Record<string, string>;
  let desktop: ElectronApplication | undefined;
  try {
    desktop = await electron.launch({ args: [join(root, 'frontend')], env, cwd: folder });
    const page = await desktop.firstWindow();
    await expect(page.getByRole('status')).toHaveText('服务就绪', { timeout: 20000 });
    await page.getByRole('button', { name: '学习', exact: true }).click();
    await page.getByRole('textbox', { name: '目标名称' }).fill('理解量子基础');
    await page.getByRole('button', { name: '添加目标', exact: true }).click();
    await expect(page.locator('.learning-goals')).toContainText('理解量子基础');
    await page.getByRole('textbox', { name: '任务名称' }).fill('阅读量子笔记');
    await page.getByRole('combobox', { name: '所属目标' }).selectOption({ label: '理解量子基础' });
    await page.getByRole('checkbox', { name: '关联提醒' }).check();
    await page.getByRole('button', { name: '添加任务', exact: true }).click();
    await expect(page.locator('.product-task')).toContainText('阅读量子笔记');
    const before = await page.evaluate(() => window.herta.productivity.snapshot());
    expect(before.tasks[0].reminder_id).toBeTruthy();
    await page.locator('.product-task').getByRole('button', { name: '延期一天' }).click();
    await expect.poll(async () => (await page.evaluate(() => window.herta.productivity.snapshot())).tasks[0].revision).toBe(before.tasks[0].revision + 1);
    const postponed = await page.evaluate(() => window.herta.productivity.snapshot());
    expect(Date.parse(postponed.tasks[0].due_at!)).toBe(Date.parse(before.tasks[0].due_at!) + 86400000);
    await page.locator('.product-task').filter({ hasText: '阅读量子笔记' }).getByRole('button', { name: '完成', exact: true }).click();
    await expect(page.locator('.learning-goals')).toContainText('1 / 1');
    const reminders = await page.evaluate(() => window.herta.companion.snapshot());
    expect(reminders.reminders.find(r => r.id === before.tasks[0].reminder_id)?.enabled).toBe(false);
    await page.getByRole('combobox', { name: '任务角色' }).selectOption('tutor');
    await page.getByRole('button', { name: '学习资料', exact: true }).click();
    await page.getByRole('textbox', { name: '学习资料名称' }).fill('量子计算');
    await page.getByRole('button', { name: '添加学习资料', exact: true }).click();
    await page.locator('.learning-material').getByRole('button', { name: '记录进度' }).click();
    await page.getByRole('spinbutton', { name: '学习进度' }).fill('60');
    await page.getByRole('button', { name: '保存进度' }).click();
    await expect(page.locator('.learning-material')).toContainText('60%');
    await page.locator('.learning-material').getByRole('button', { name: '记录复习' }).click();
    await expect(page.locator('.learning-material')).toContainText('复习 1 次');
    await page.getByRole('button', { name: '复述对照', exact: true }).click();
    await page.getByRole('textbox', { name: '复述原文' }).fill('量子比特描述叠加态');
    await page.getByRole('textbox', { name: '复述转写' }).fill('量子描述叠加态');
    await page.getByRole('button', { name: '对照原文' }).click();
    await expect(page.locator('.recitation-result')).toContainText('比特');
    await expect(page.locator('.recitation-result')).toContainText('文字对照');
    await page.screenshot({ path: join(root, '.local/productivity-desktop.png') });
    await page.getByRole('button', { name: '关闭学习工作台' }).click();
    await desktop.close(); desktop = undefined;
    desktop = await electron.launch({ args: [join(root, 'frontend')], env, cwd: folder });
    const reopened = await desktop.firstWindow();
    await expect(reopened.getByRole('status')).toHaveText('服务就绪', { timeout: 20000 });
    const persisted = await reopened.evaluate(() => window.herta.productivity.snapshot());
    expect(persisted.role).toBe('tutor'); expect(persisted.materials[0].progress).toBe(60); expect(persisted.tasks[0].status).toBe('completed');
  } finally { await desktop?.close(); await rm(folder, { recursive: true, force: true }); }
});
